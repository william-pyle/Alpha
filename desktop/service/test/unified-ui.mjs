import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { expect } from '@playwright/test';
import { createService } from '../server.mjs';
import { launchBrowser } from './browser.mjs';
import { packageLibrary } from '../../../scripts/package-library.mjs';

await mkdir('.test-output', { recursive: true });
const repo = await mkdtemp(path.resolve('.test-output/unified-ui-'));
await mkdir(path.join(repo, 'workspace/example'), { recursive: true });
await writeFile(path.join(repo, 'workspace/example/report.html'), '<h1>Document one</h1>');
await writeFile(path.join(repo, 'workspace/workspace.json'), JSON.stringify({ entities: [{ id: 'example', title: 'Example project', description: 'An isolated desktop test', folder: 'example', category: 'project', status: 'active', sample: true, created: '2026-11-08', steps: [{ name: 'Report', path: 'report.html' }] }] }));
const bundle = path.join(repo, 'library-bundle'); await packageLibrary(bundle);
const service = await createService({ repo, uiDir: path.resolve('dist'), sharedLibrary: { bundle, root: path.join(repo, 'SharedLibrary') }, mcpOptions: { home: repo, env: {}, probe: async () => ({ status: 'available' }) } });
let browser;
try {
  browser = await launchBrowser();
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(service.urls.workspace);
  await expect(page.getByRole('tablist', { name: 'Documents' })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'Workspace' })).toBeVisible();
  await expect(page.locator('.mdi-chats')).toBeVisible();
  await expect(page.locator('.mdi-statusbar')).toContainText('Connected');
  await page.screenshot({ path: '.test-output/unified-home.png' });
  await page.getByRole('button', { name: 'File', exact: true }).click();
  await page.getByRole('menuitem', { name: 'New card' }).click();
  await expect(page.getByRole('dialog', { name: 'New Workspace card' })).toBeVisible();
  await page.getByRole('button', { name: 'Close new card' }).click();
  await page.getByRole('button', { name: 'Tools', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Settings…' }).click();
  await expect(page.getByRole('dialog', { name: 'Settings' })).toBeVisible();
  await page.getByRole('tab', { name: 'Categories' }).click();
  await expect(page.getByRole('heading', { name: 'Card categories' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Add category' })).toBeVisible();
  await page.getByLabel('Name', { exact: true }).fill('Writing');
  await page.getByRole('button', { name: 'Add category' }).click();
  await expect(page.getByText('Writing', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit Writing' }).click();
  await page.getByLabel('Name', { exact: true }).fill('Writing Notes');
  await page.getByRole('button', { name: 'Save category' }).click();
  await expect(page.getByText('Writing Notes', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete Writing Notes' }).click();
  await page.getByRole('button', { name: 'Delete category' }).click();
  await expect(page.getByRole('button', { name: 'Delete Writing Notes' })).toHaveCount(0);
  await page.screenshot({ path: '.test-output/unified-settings.png' });
  await page.getByRole('tab', { name: 'Skills' }).click();
  await expect(page.getByRole('heading', { name: 'Skills' })).toBeVisible();
  await page.getByRole('tab', { name: 'MCP' }).click();
  await expect(page.getByText('MCP', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Close settings' }).last().click();
  await page.getByRole('button', { name: 'Help', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Open Help' }).click();
  await expect(page.getByRole('tab', { name: 'Help' })).toBeVisible();
  await expect(page.frameLocator('iframe').getByText('Alpha combines Chats and Workspace')).toBeVisible();
  await page.screenshot({ path: '.test-output/unified-help.png' });
  await page.getByRole('tab', { name: 'Workspace' }).click();
  await page.getByText('Example project', { exact: true }).last().click();
  await expect(page.getByRole('tab', { name: 'Example project' })).toBeVisible();
  await expect(page.frameLocator('iframe').getByText('Document one')).toBeVisible();
  await page.screenshot({ path: '.test-output/unified-document.png' });
  assert.deepEqual(errors, []);
  console.log('Unified Alpha layout passed: one surface, document tabs, New Card dialog, Settings sections, Help tab and statusbar.');
} finally { await browser?.close(); await service.close(); }
