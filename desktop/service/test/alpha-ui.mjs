  assert.equal(saved.appTheme, 'higurashi'); assert.equal(saved.defaultBypass, true);
  assert.deepEqual(errors, []);
  await writeFile('.test-output/alpha-ui-result.json', JSON.stringify({ passed: true, repo, checks: ['Four providers','Phone routes removed','Both windows retain workflow','Three synchronized themes','Always approve','Real Git Bash with working folder','Real PowerShell','History','Report navigation','File preview','Persisted preferences'] }, null, 2));
